"""Phase 2: the naive Java call graph and the audit of how it fails.

Naive graph (the Java analogue of Paper 1's L0/L1): one edge owner -> T per
method call, where T is the declared static type of the receiver. Calls with
no receiver, or on `this`/`super`, or static calls through a type name, bind
to the declaring type of the resolved method. Nothing else: no hierarchy, no
injection, no XML.

Every call site is classified into exactly one category:

  edge_concrete  T is a concrete application class other than the owner
  self           T is the owner itself
  inherited      a call on this/super (explicit or implicit) that binds to a
                 method of an application supertype: a real structural edge
                 to the supertype, as Paper 1's L2 produced for Ruby mixins
  external       T resolved to a library or JDK type (not a lookup)
  J1_dispatch    T is an application interface or abstract class that has at
                 least one concrete application subtype: the edge lands on the
                 abstraction and the implementation receives nothing
  J4_no_impl     T is an application interface with no concrete application
                 subtype: its implementation is generated by a framework or
                 lives outside Java (MyBatis XML, container proxies)
  J3_reflective  a JNDI lookup, Class.forName, getBean, loadClass or
                 newInstance call: the collaborator is named by a string
  J6_unresolved  the symbol solver could neither type the receiver nor bind
                 the method

Overlays, counted separately because they cut across categories:
  J2  injection points (annotated fields, constructor and setter parameters,
      Spring XML properties) and the call sites made through them
  J5  classes that are entry points wired from outside Java (web.xml,
      faces-config, JSF EL, JSP/Stripes bean classes, Struts actions) and the
      number of them with no inbound naive edge

Usage: python3 -m java_pipeline.audit [app ...]
Writes results/<app>/naive_graph.json, results/<app>/audit/audit.json,
results/<app>/audit/sample.jsonl and results/audit_table.csv.
"""
