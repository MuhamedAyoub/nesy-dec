# Calls that name their collaborator by a string, keyed by method, with the
# receiver types that make them reflective. None = receiver unresolved, which
# only counts for lookup/getBean (the classpath-less literature variants).
REFLECTIVE = {
    "lookup": ("javax.naming.",), "lookupLink": ("javax.naming.",),
    "forName": ("java.lang.Class",), "newInstance": ("java.lang.Class", "java.lang.reflect.Constructor"),
    "loadClass": ("java.lang.ClassLoader",), "getBean": ("org.springframework.",),
}


def is_reflective(c: dict, t: str | None) -> bool:
    prefixes = REFLECTIVE.get(c["method"])
    if not prefixes:
        return False
    if t is None:
        return c["method"] in ("lookup", "getBean")
    return any(t == p or t.startswith(p) for p in prefixes) or t.endswith("ClassLoader")
DI_ANNOTATIONS = ("Inject", "EJB", "Resource", "Autowired", "PersistenceContext", "PersistenceUnit", "SpringBean")
# Classes whose single constructor the container calls with injected arguments
# (Spring component scanning, CDI): their constructor parameters are injection points.
MANAGED_STEREOTYPES = ("Service", "Component", "Repository", "Controller", "RestController",
                       "ApplicationScoped", "RequestScoped", "SessionScoped", "Dependent", "Stateless", "Singleton")
JPA_ASSOC = ("OneToMany", "ManyToOne", "OneToOne", "ManyToMany")
EXAMPLES_PER_CATEGORY = 3
SAMPLE_SIZE = 40
SEED = 42


# ---------------------------------------------------------------- loading

def load(app: str):
    d = facts_dir(app)
    inv = json.loads((d / "inventory.json").read_text())
    calls = [json.loads(l) for l in (d / "callsites.jsonl").read_text().splitlines() if l.strip()]
    creations = [json.loads(l) for l in (d / "creations.jsonl").read_text().splitlines() if l.strip()]
    run = json.loads((d / "run.json").read_text())
    return inv, calls, creations, run


_line_cache: dict[str, list[str]] = {}


def source_line(file: str, line: int) -> str:
    if file not in _line_cache:
        _line_cache[file] = Path(file).read_text(encoding="utf-8", errors="replace").splitlines()
    lines = _line_cache[file]
    return lines[line - 1].strip() if 0 < line <= len(lines) else ""


def rel(file: str) -> str:
    try:
        return str(Path(file).relative_to(DATA))
    except ValueError:
        return file


def ann_name(a: str) -> str:
    return a.lstrip("@").split("(")[0].split(".")[-1]


# -------------------------------------------------------------- hierarchy

class Hierarchy:
    """Application types, their supertypes, and concrete subtypes."""

    def __init__(self, inv: list[dict]):
        self.types = {t["name"]: t for t in inv}
        self.supers: dict[str, set[str]] = {}
        for t in inv:
            s = set()
            for ref in t["extends"] + t["implements"]:
                s.add(ref["resolved"] or ref["raw"])
            self.supers[t["name"]] = s
        self.subs: dict[str, set[str]] = defaultdict(set)
        for t in self.types:
            for s in self.all_supers(t):
                self.subs[s].add(t)

    def all_supers(self, t: str, seen: set | None = None) -> set[str]:
        seen = set() if seen is None else seen
        for s in self.supers.get(t, ()):
            if s not in seen:
                seen.add(s)
                self.all_supers(s, seen)
        return seen

    def is_abstraction(self, t: str) -> bool:
        x = self.types.get(t)
        return bool(x) and (x["kind"] == "interface" or (x["kind"] == "class" and x["abstract"]))

    def concrete_impls(self, t: str) -> list[str]:
        return sorted(s for s in self.subs.get(t, ())
                      if s in self.types and not self.is_abstraction(s)
                      and self.types[s]["kind"] in ("class", "enum", "record"))


# ---------------------------------------------------------------- classify

def naive_target(c: dict, h: "Hierarchy | None" = None) -> tuple[str | None, str]:
    """Declared static receiver type, else the binding declaration's type.

    An unbound call on this (explicit or implicit) counts as a self call only
    when the owner itself declares a method of that name; otherwise it binds
    to an unresolved supertype and is reported as unresolved, not hidden."""
    if c["scope_kind"] in ("implicit", "ThisExpr", "SuperExpr"):
        if c["decl_type"]:
            return c["decl_type"], "decl"
        if c["scope_kind"] != "SuperExpr" and h is not None and c["owner"] in h.types and any(
                m["name"] == c["method"] for m in h.types[c["owner"]]["methods"]):
            return c["owner"], "owner"
        return None, "none"
    if c["receiver_type"]:
        return c["receiver_type"], "receiver"
    if c["decl_type"] and c["decl_static"]:
        return c["decl_type"], "static"
    if c["decl_type"]:
        return c["decl_type"], "decl"
    return None, "none"


def classify(c: dict, h: Hierarchy) -> tuple[str, str | None]:
    t, _ = naive_target(c, h)
    if is_reflective(c, t):
        return "J3_reflective", t
    if t is None:
        return "J6_unresolved", None
    if t.endswith("[]"):
        t = t[:-2]
    if t == c["owner"]:
        return "self", t
    if t not in h.types:
        return "external", t
    if c["scope_kind"] in ("implicit", "ThisExpr", "SuperExpr"):
        return "inherited", t
    if h.is_abstraction(t):
        return ("J1_dispatch" if h.concrete_impls(t) else "J4_no_impl"), t
    return "edge_concrete", t


# --------------------------------------------------------- non-Java wiring

def xml_files(app: str) -> list[Path]:
    out = []
    for r in SUBJECTS[app]["roots"]:
        module = (DATA / r).parents[2]          # <module>/src/main/java -> <module>
        for p in module.rglob("*.xml"):
            s = str(p)
            if "/src/main/" in s and not any(x in s for x in ("/target/", "/build/", "/.git/")):
                out.append(p)
    return sorted(set(out))


_XML_COMMENT = re.compile(r"<!--.*?-->", re.S)


def xml_text(p: Path) -> str:
    """XML file text with comments blanked out (line numbers preserved), so a
    commented-out <bean> or <mapper> is not read as configuration."""
    text = p.read_text(encoding="utf-8", errors="replace")
    return _XML_COMMENT.sub(lambda m: re.sub(r"[^\n]", " ", m.group(0)), text)


def page_files(app: str) -> list[Path]:
    out = []
    for r in SUBJECTS[app]["roots"]:
        module = (DATA / r).parents[2]
        for ext in ("*.jsp", "*.jspf", "*.xhtml", "*.html", "*.tag"):
            out += [p for p in module.rglob(ext) if "/src/main/" in str(p)]
    return sorted(set(out))


FQCN_RX = re.compile(r"\b([a-z][\w]*(?:\.[a-z][\w]*)+\.[A-Z][\w$]*)")


def external_wiring(app: str, h: Hierarchy) -> dict:
    """Classes named from XML and pages, by source file kind."""
    refs: dict[str, set[str]] = defaultdict(set)   # source kind -> app classes named
    examples: list[str] = []
    for p in xml_files(app):
        text = xml_text(p)
        kind = p.name if p.name in ("web.xml", "faces-config.xml", "ejb-jar.xml", "persistence.xml",
                                    "struts-config.xml", "beans.xml") else (
            "spring-dispatcher-xml" if p.name.endswith("-servlet.xml") else
            "spring-xml" if re.search(r"<bean\b", text) else
            "mybatis-mapper-xml" if "<mapper" in text else
            "ibatis-sqlmap-xml" if "<sqlMap" in text else "other-xml")
        for m in FQCN_RX.finditer(text):
            n = m.group(1).replace("$", ".")
            if n in h.types:
                refs[kind].add(n)
                if len(examples) < 6:
                    ln = text[:m.start()].count("\n") + 1
                    examples.append(f"{rel(str(p))}:{ln}  {n}")
    # JSF EL / JSP: #{bean.x} or ${bean.x} resolved against @Named / @ManagedBean names
    named = {}
    for t, x in h.types.items():
        for a in x["annotations"]:
            if ann_name(a) in ("Named", "ManagedBean"):
                m = re.search(r'"([^"]+)"', a)
                simple = t.split(".")[-1]
                named[m.group(1) if m else simple[0].lower() + simple[1:]] = t
    el_hits = Counter()
    for p in page_files(app):
        text = p.read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(r"[#$]\{\s*([A-Za-z_]\w*)", text):
            if m.group(1) in named:
                el_hits[named[m.group(1)]] += 1
        for m in FQCN_RX.finditer(text):
            n = m.group(1)
            if n in h.types:
                refs["pages(fqcn)"].add(n)
    for t in el_hits:
        refs["pages(EL)"].add(t)
    # annotation-declared entry points
    for t, x in h.types.items():
        for a in x["annotations"]:
            if ann_name(a) in ("WebServlet", "WebFilter", "WebListener", "Path", "ApplicationPath",
                               "ServerEndpoint", "MessageDriven", "UrlBinding"):
                refs["annotation-entry-point"].add(t)
    return {"refs": {k: sorted(v) for k, v in refs.items()}, "examples": examples,
            "el_reference_counts": dict(el_hits)}


# Sources that name request entry points (as opposed to service-layer wiring
# such as applicationContext beans, persistence units or SQL maps).
ENTRY_KINDS = ("web.xml", "faces-config.xml", "struts-config.xml", "spring-dispatcher-xml",
               "pages(fqcn)", "pages(EL)", "annotation-entry-point")


def spring_xml_injections(app: str, h: Hierarchy) -> list[dict]:
    """Spring XML wiring: each <property>/<constructor-arg> that references
    another bean, with the bean classes on both ends when they are declared.
    `app_involved` is true when either end is an application class."""
    out = []
    for p in xml_files(app):
        text = xml_text(p)
        if not re.search(r"<bean\b", text):
            continue
        ids = {}
        for b in re.finditer(r"<bean\b([^>]*?)/?>", text):
            i = re.search(r'\b(?:id|name)="([^"]+)"', b.group(1))
            c = re.search(r'\bclass="([^"]+)"', b.group(1))
            if i and c:
                ids[i.group(1)] = c.group(1)
        for b in re.finditer(r"<bean\b([^>]*?)(?<!/)>(.*?)</bean>", text, re.S):
            cls = re.search(r'\bclass="([^"]+)"', b.group(1))
            bean_class = cls.group(1) if cls else None
            for tag in re.finditer(r"<(property|constructor-arg)\b([^>]*)>(.*?)(?:</\1>|$)|<(property|constructor-arg)\b([^>]*)/>",
                                   b.group(2), re.S):
                kind = tag.group(1) or tag.group(4)
                attrs = (tag.group(2) or tag.group(5) or "")
                body = tag.group(3) or ""
                name = re.search(r'\bname="([^"]+)"', attrs)
                ref = re.search(r'\bref="([^"]+)"', attrs) or re.search(r'<ref\s+(?:bean|local)="([^"]+)"', body)
                if not ref:
                    continue
                ref_class = ids.get(ref.group(1))
                out.append({"file": rel(str(p)), "line": text[:b.start()].count("\n") + 1,
                            "bean_class": bean_class, "kind": kind,
                            "name": name.group(1) if name else None, "ref": ref.group(1), "ref_class": ref_class,
                            "app_involved": bean_class in h.types or ref_class in h.types})
    return out


IBATIS_CALLS = {"insert", "update", "delete", "queryForObject", "queryForList", "queryForMap",
                "queryForPaginatedList", "queryWithRowHandler"}


def mapper_xml(app: str, h: Hierarchy, calls: list[dict]) -> dict:
    """SQL-mapping XML and the application classes it binds.

    MyBatis: <mapper namespace="I"> binds interface I; resultType/parameterType
    name domain classes either fully qualified or through aliases
    (typeAliasesPackage, <typeAliases><package>, <typeAlias>).
    iBatis 2: <sqlMap> statements are reached from DAO code by statement-id
    strings (getSqlMapClientTemplate().insert("insertAccount", ...)); domain
    classes appear in resultMap/parameterMap class="...".
    Returns, per binder (mapper interface or DAO class), the domain classes
    its SQL maps to."""
    texts = {p: xml_text(p) for p in xml_files(app)}
    alias_pkgs, aliases = set(), {}
    for t in texts.values():
        for m in re.finditer(r'name="typeAliasesPackage"\s+value="([^"]+)"', t):
            alias_pkgs |= {x.strip() for x in re.split(r"[,;]", m.group(1)) if x.strip()}
        for m in re.finditer(r"<typeAliases>(.*?)</typeAliases>", t, re.S):
            alias_pkgs |= set(re.findall(r'<package\s+name="([^"]+)"', m.group(1)))
        for m in re.finditer(r'<typeAlias\s+[^>]*alias="([^"]+)"[^>]*type="([^"]+)"', t):
            aliases[m.group(1).lower()] = m.group(2)

    def resolve(v: str) -> str | None:
        if v in h.types:
            return v
        if v.lower() in aliases and aliases[v.lower()] in h.types:
            return aliases[v.lower()]
        hits = [t for t in h.types if t.rsplit(".", 1)[0] in alias_pkgs and t.split(".")[-1].lower() == v.lower()]
        return hits[0] if len(hits) == 1 else None

    attr = re.compile(r'\b(?:resultType|parameterType|ofType|javaType|resultClass|parameterClass|type|class)="([^"]+)"')
    binders: dict[str, set[str]] = defaultdict(set)
    kinds, files = {}, {}
    stmt_owner: dict[str, str] = {}               # iBatis statement id -> sqlmap file
    stmt_types: dict[str, set[str]] = defaultdict(set)
    for p, t in texts.items():
        m = re.search(r'<mapper\s+namespace="([^"]+)"', t)
        if m:
            ns = m.group(1)
            kinds[ns], files[ns] = "mybatis", rel(str(p))
            binders[ns] |= {r for v in attr.findall(t) if (r := resolve(v))}
        elif "<sqlMap" in t:
            types = {r for v in attr.findall(t) if (r := resolve(v))}
            key = rel(str(p))
            stmt_types[key] = types
            for sid in re.findall(r'<(?:select|insert|update|delete|statement|procedure)\s+[^>]*id="([^"]+)"', t):
                stmt_owner[sid] = key
    # iBatis: the DAO class that names a statement id binds that sqlmap's types
    ibatis_links = set()
    for c in calls:
        a0 = c.get("arg0") or {}
        if c["method"] in IBATIS_CALLS and a0.get("kind") == "StringLiteralExpr" and a0.get("value") in stmt_owner:
            key = stmt_owner[a0["value"]]
            ibatis_links.add((c["owner"], key))
            binders[c["owner"]] |= stmt_types[key]
            kinds[c["owner"]], files[c["owner"]] = "ibatis", key
    return {"binders": {k: sorted(v) for k, v in binders.items()}, "kinds": kinds, "files": files,
            "alias_packages": sorted(alias_pkgs), "ibatis_dao_sqlmap_links": len(ibatis_links),
            "sql_xml_files": sum(1 for t in texts.values() if "<mapper" in t or "<sqlMap" in t)}


# ------------------------------------------------------------------- audit

def audit(app: str) -> dict:
    inv, calls, creations, run = load(app)
    h = Hierarchy(inv)
    app_calls = [c for c in calls if c["owner"] in h.types]

    graph: dict[str, Counter] = defaultdict(Counter)
    cats = Counter()
    by_cat: dict[str, list[dict]] = defaultdict(list)
    for c in app_calls:
        cat, t = classify(c, h)
        c["_cat"], c["_target"] = cat, t
        cats[cat] += 1
        by_cat[cat].append(c)
        if cat in ("edge_concrete", "inherited", "J1_dispatch", "J4_no_impl"):
            graph[c["owner"]][t] += 1
    for t in h.types:
        graph.setdefault(t, Counter())

    # J1 ------------------------------------------------------------------
    abstractions = [t for t in h.types if h.is_abstraction(t)]
    impl_counts = {t: len(h.concrete_impls(t)) for t in abstractions}
    j1_sites_by_n = Counter()
    for c in by_cat["J1_dispatch"]:
        n = impl_counts[c["_target"]]
        j1_sites_by_n["1" if n == 1 else ">=2"] += 1
    lost_impl_edges = set()
    for c in by_cat["J1_dispatch"]:
        for i in h.concrete_impls(c["_target"]):
            if i != c["owner"] and graph[c["owner"]].get(i, 0) == 0:
                lost_impl_edges.add((c["owner"], i))

    # J2 ------------------------------------------------------------------
    di_points, di_fields = [], set()
    for t, x in h.types.items():
        for f in x["fields"]:
            anns = [ann_name(a) for a in f["annotations"]]
            hit = [a for a in anns if a in DI_ANNOTATIONS]
            if hit:
                ty = f["type"].get("erasure")
                di_points.append({"owner": t, "member": f["name"], "via": hit[0], "type": ty,
                                  "type_class": ("app-abstraction" if ty in h.types and h.is_abstraction(ty)
                                                 else "app-concrete" if ty in h.types else "external"),
                                  "where": f"{rel(x['file'])}:{f['line']}"})
                di_fields.add((t, f["name"]))
        managed = any(ann_name(a) in MANAGED_STEREOTYPES for a in x["annotations"])
        for k in x["constructors"]:
            annotated = any(ann_name(a) in DI_ANNOTATIONS for a in k["annotations"])
            implicit = managed and len(x["constructors"]) == 1 and k["params"]
            if not (annotated or implicit):
                continue
            for p in k["params"]:
                ty = p["type"].get("erasure")
                di_points.append({"owner": t, "member": p["name"],
                                  "via": "ctor-annotated" if annotated else "ctor-implicit", "type": ty,
                                  "type_class": ("app-abstraction" if ty in h.types and h.is_abstraction(ty)
                                                 else "app-concrete" if ty in h.types else "external"),
                                  "where": f"{rel(x['file'])}:{k['line']}"})
                # constructor-injected values are kept in a field of the same
                # name in every benchmark class audited; join on that name
                if any(f["name"] == p["name"] for f in x["fields"]):
                    di_fields.add((t, p["name"]))
    spring = spring_xml_injections(app, h)
    j2_sites = [c for c in app_calls if c.get("scope_field") and (c["owner"], c["scope_field"]) in di_fields]
    j2_cat = Counter(c["_cat"] for c in j2_sites)

    # J3 ------------------------------------------------------------------
    j3 = by_cat["J3_reflective"]
    j3_literal = Counter()
    for c in j3:
        a = c.get("arg0") or {}
        j3_literal[(c["method"], "literal" if a.get("kind") == "StringLiteralExpr" else "non-literal")] += 1

    # J4 ------------------------------------------------------------------
    mx = mapper_xml(app, h, app_calls)
    no_impl_ifaces = sorted(t for t in abstractions if impl_counts[t] == 0 and h.types[t]["kind"] == "interface")
    no_impl_with_xml = [t for t in no_impl_ifaces if mx["kinds"].get(t) == "mybatis"]
    mapper_pairs = [(b, ty) for b, tys in mx["binders"].items() if b in h.types for ty in tys if ty != b]
    mapper_lost = [(b, ty) for b, ty in mapper_pairs if graph[b].get(ty, 0) == 0]
    assoc, assoc_missing = [], []
    for t, x in h.types.items():
        for f in x["fields"]:
            hit = [ann_name(a) for a in f["annotations"] if ann_name(a) in JPA_ASSOC]
            if not hit:
                continue
            ty = f["type"].get("erasure")
            args = f["type"].get("args") or []
            target = next((a for a in [ty] + args if a in h.types), None)
            assoc.append({"entity": t, "field": f["name"], "kind": hit[0], "target": target,
                          "where": f"{rel(x['file'])}:{f['line']}"})
            if target and graph[t].get(target, 0) == 0 and graph[target].get(t, 0) == 0:
                assoc_missing.append((t, target))

    simple = defaultdict(list)
    for t in h.types:
        simple[t.split(".")[-1]].append(t)
    lit_sites, lit_pairs, lit_missing = [], set(), set()
    for c in by_cat["external"] + by_cat["J6_unresolved"]:
        a0 = c.get("arg0") or {}
        if a0.get("kind") != "ClassExpr":
            continue
        name = a0["value"].split("<")[0]
        cands = [name] if name in h.types else simple.get(name.split(".")[-1], [])
        if len(cands) == 1 and cands[0] != c["owner"]:
            lit_sites.append(c)
            lit_pairs.add((c["owner"], cands[0]))
            if graph[c["owner"]].get(cands[0], 0) == 0:
                lit_missing.add((c["owner"], cands[0]))

    # J5 ------------------------------------------------------------------
    wiring = external_wiring(app, h)
    inbound = Counter()
    for s, es in graph.items():
        for t, w in es.items():
            if t != s:
                inbound[t] += w
    entry = sorted({t for k in ENTRY_KINDS for t in wiring["refs"].get(k, [])
                    if h.types[t]["kind"] == "class"})
    entry_no_inbound = [t for t in entry if inbound[t] == 0]

    # J6 ------------------------------------------------------------------
    j6 = by_cat["J6_unresolved"]
    j6_err = Counter((c["receiver_error"] or c["decl_error"] or "").split(":")[0] for c in j6)
    j6_symbols, j6_module = Counter(), Counter()
    for c in j6:
        # "Unsolved symbol : Foo" or "Unsolved symbol in <expr> : Foo"
        e = c["receiver_error"] or c["decl_error"] or "?"
        m = (re.search(r"Unsolved symbol in ([\w.$]+) : Solving", e)
             or re.search(r"corresponding to (\w+)\(", e)
             or re.search(r"Unsolved symbol(?: in .*?)? : ([\w.$]+)", e))
        if m and "corresponding to" in e:
            key = f"method {m.group(1)}() unbound"
        else:
            key = m.group(1) if m else "(no symbol named) " + " ".join(e.split(":", 1)[-1].split()[:4])
        j6_symbols[key] += 1
        j6_module[next((r for r in SUBJECTS[app]["roots"] if str(DATA / r) in c["file"]), "?")] += 1
    unresolved_type_refs = sum(1 for x in h.types.values()
                               for r in x["extends"] + x["implements"] if not r["resolved"])
    unresolved_field_types = sum(1 for x in h.types.values() for f in x["fields"] if not f["type"].get("erasure"))

    # J7 (found in this audit): dependencies that exist only as declared types
    # (fields, constructor and method parameters, return types, type arguments)
    # and never as a call in either direction.
    type_use: dict[tuple[str, str], str] = {}
    def note(owner: str, ti: dict, where: str) -> None:
        for ty in [ti.get("erasure")] + list(ti.get("args") or []):
            if ty and ty.endswith("[]"):
                ty = ty[:-2]
            if ty in h.types and ty != owner and (owner, ty) not in type_use:
                type_use[(owner, ty)] = where
    for t, x in h.types.items():
        for f in x["fields"]:
            note(t, f["type"], f"{rel(x['file'])}:{f['line']}")
        for k in x["constructors"]:
            for pp in k["params"]:
                note(t, pp["type"], f"{rel(x['file'])}:{k['line']}")
        for m in x["methods"]:
            note(t, m["returns"], f"{rel(x['file'])}:{m['line']}")
            for pp in m["params"]:
                note(t, pp["type"], f"{rel(x['file'])}:{m['line']}")
    type_only = {k: v for k, v in type_use.items() if graph[k[0]].get(k[1], 0) == 0 and graph[k[1]].get(k[0], 0) == 0}

    # examples --------------------------------------------------------------
    def ex(cs: list[dict]) -> list[str]:
        return [f"{rel(c['file'])}:{c['line']}  {source_line(c['file'], c['line'])[:140]}"
                f"   [owner={c['owner'].split('.')[-1]}, target={(c['_target'] or '?').split('.')[-1]}]"
                for c in cs[:EXAMPLES_PER_CATEGORY]]

    rng = random.Random(SEED)
    sample = rng.sample(app_calls, min(SAMPLE_SIZE, len(app_calls)))

    edges = sum(1 for s, es in graph.items() for t in es if t != s)
    result = {
        "app": app,
        "class_nodes": len(h.types),
        "kinds": dict(Counter(x["kind"] for x in h.types.values())),
        "call_sites": len(app_calls),
        "categories": dict(cats),
        "naive_edges": edges,
        "isolated_nodes": sum(1 for t in h.types if not graph[t] and inbound[t] == 0),
        "J1": {
            "abstractions": len(abstractions),
            "with_0_impl": sum(1 for n in impl_counts.values() if n == 0),
            "with_1_impl": sum(1 for n in impl_counts.values() if n == 1),
            "with_2plus_impl": sum(1 for n in impl_counts.values() if n >= 2),
            "call_sites": cats["J1_dispatch"],
            "call_sites_by_impl_count": dict(j1_sites_by_n),
            "lost_owner_impl_pairs": len(lost_impl_edges),
            "multi_impl_abstractions": {t: h.concrete_impls(t) for t in abstractions if impl_counts[t] >= 2},
            "examples": ex(by_cat["J1_dispatch"]),
        },
        "J2": {
            "annotated_injection_points": len(di_points),
            "by_annotation": dict(Counter(d["via"] for d in di_points)),
            "by_declared_type": dict(Counter(d["type_class"] for d in di_points)),
            "spring_xml_injections": len(spring),
            "spring_xml_injections_involving_app_classes": sum(1 for s in spring if s["app_involved"]),
            "call_sites_through_injected_fields": len(j2_sites),
            "those_call_sites_by_category": dict(j2_cat),
            "examples": [f"{d['where']}  @{d['via']} {d['type']} {d['member']}" for d in di_points[:3]]
                        + [f"{s['file']}:{s['line']}  bean {s['bean_class']} {s['kind']} {s['name']} -> {s['ref']} ({s['ref_class']})"
                           for s in spring if s["app_involved"]][:3],
        },
        "J3": {
            "call_sites": len(j3),
            "by_method_and_argument": {f"{m}/{k}": v for (m, k), v in sorted(j3_literal.items())},
            "jndi_literal_names": sorted({(c.get("arg0") or {}).get("value") for c in j3
                                          if (c.get("arg0") or {}).get("kind") == "StringLiteralExpr"}),
            "examples": ex(j3),
        },
        "J4": {
            "interfaces_without_java_impl": no_impl_ifaces,
            "of_which_bound_by_mapper_xml": no_impl_with_xml,
            "call_sites_on_interfaces_without_impl": cats["J4_no_impl"],
            "sql_xml_files": mx["sql_xml_files"],
            "alias_packages": mx["alias_packages"],
            "ibatis_dao_sqlmap_links": mx["ibatis_dao_sqlmap_links"],
            "binder_to_mapped_type_pairs": len(mapper_pairs),
            "binder_to_mapped_type_pairs_missing_in_naive_graph": len(mapper_lost),
            "missing_pairs": [f"{b.split('.')[-1]} -> {t.split('.')[-1]} ({mx['kinds'][b]}, {mx['files'][b]})"
                              for b, t in sorted(mapper_lost)],
            "class_literal_sites_on_external_receivers": len(lit_sites),
            "class_literal_receiver_types": dict(Counter((c["_target"] or "?").split(".")[-1] for c in lit_sites)),
            "class_literal_owner_target_pairs": len(lit_pairs),
            "class_literal_pairs_missing_in_naive_graph": len(lit_missing),
            "class_literal_examples": ex(lit_sites),
            "jpa_associations": len(assoc),
            "jpa_association_pairs_missing_in_naive_graph": len(set(assoc_missing)),
            "examples": ex(by_cat["J4_no_impl"]) + [f"{a['where']}  @{a['kind']} {a['field']} -> {a['target']}" for a in assoc[:2]],
        },
        "J5": {
            "classes_named_outside_java": {k: len(v) for k, v in wiring["refs"].items()},
            "entry_point_sources": [k for k in ENTRY_KINDS if wiring["refs"].get(k)],
            "entry_point_classes": len(entry),
            "entry_points_without_inbound_naive_edge": len(entry_no_inbound),
            "el_reference_counts": wiring["el_reference_counts"],
            "examples": wiring["examples"][:4],
        },
        "J6": {
            "call_sites": len(j6),
            "share_of_call_sites": round(len(j6) / max(1, len(app_calls)), 4),
            "by_error": dict(j6_err),
            "top_unsolved_symbols": dict(j6_symbols.most_common(10)),
            "by_module": dict(j6_module),
            "unresolved_supertype_refs": unresolved_type_refs,
            "unresolved_field_types": unresolved_field_types,
            "jars_loaded": run["jars_loaded"],
            "examples": ex(j6),
        },
        "J7": {
            "type_use_pairs": len(type_use),
            "type_use_pairs_without_call_edge": len(type_only),
            "examples": [f"{w}  {o.split('.')[-1]} declares type {t.split('.')[-1]}" for (o, t), w in sorted(type_only.items())[:4]],
        },
        "object_creations_of_app_classes": sum(1 for o in creations if o["owner"] in h.types and o["type"] in h.types),
    }

    # outputs ----------------------------------------------------------------
    adir = OUT / app / "audit"
    adir.mkdir(parents=True, exist_ok=True)
    (adir / "audit.json").write_text(json.dumps(result, indent=2))
    with (adir / "sample.jsonl").open("w") as f:
        for c in sample:
            f.write(json.dumps({"where": f"{rel(c['file'])}:{c['line']}", "code": source_line(c["file"], c["line"]),
                                "owner": c["owner"], "category": c["_cat"], "target": c["_target"],
                                "receiver_type": c["receiver_type"], "decl_type": c["decl_type"],
                                "error": c["receiver_error"] or c["decl_error"]}) + "\n")
    naive = {
        "parameters": {"resolver": "java-naive", "rule": "declared static receiver type"},
        "summary": {"total_classes_original": len(h.types), "naive_edges": edges},
        "resolver_report": dict(cats),
        "dependency_graph": {s: dict(es) for s, es in sorted(graph.items())},
        "data_associations": {},
        "clusters": [],
    }
    (OUT / app / "naive_graph.json").write_text(json.dumps(naive, indent=2))
    return result


